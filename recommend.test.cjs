const assert=require('node:assert/strict');
const catalog=require('./catalog.js');
const {budgetAllows,recommendGifts}=require('./recommend.js');
const base={recipient:'A friend',pet:'Dog',occasion:'Birthday',preference:'Something funny',budget:'Up to $25'};
assert.equal(budgetAllows(2500,'Up to $25'),true);
assert.equal(budgetAllows(2500,'Over $25 to $50'),false);
assert.equal(budgetAllows(5000,'Over $25 to $50'),true);
assert.equal(budgetAllows(5001,'Over $50 to $75'),true);
assert.equal(budgetAllows(7500,'Over $75'),false);
assert.equal(recommendGifts(catalog,base)[0].product.id,'magnet-photo');
assert.equal(recommendGifts(catalog,{...base,occasion:"Mother’s / Father’s Day"})[0].product.id,'socks-photo');
assert.equal(recommendGifts(catalog,{...base,pet:'Another pet'}).length,0);
assert.equal(recommendGifts(catalog,{...base,budget:'Over $50 to $75'})[0].product.id,'blanket-heads');
assert.equal(recommendGifts(catalog,{...base,budget:'Over $50 to $75'})[0].variant.priceCents,5995);
assert.equal(recommendGifts(catalog,{...base,budget:'Over $75'})[0].variant.priceCents,7995);
assert.equal(recommendGifts(catalog,{...base,pet:'Horse'}).some(r=>r.product.id==='socks-photo'),false);
assert.equal(recommendGifts(catalog.map(p=>({...p,verified:false})),base).length,0);
assert.equal(recommendGifts(catalog.map(p=>({...p,variants:p.variants.map(v=>({...v,available:false}))})),base).length,0);
const ranked=recommendGifts(catalog,{...base,budget:'No set budget'});
assert.equal(new Set(ranked.map(r=>r.product.id)).size,ranked.length);
assert.deepEqual(recommendGifts(catalog,base),recommendGifts(catalog,base));
const poster=recommendGifts(catalog,{...base,budget:'Over $25 to $50'})[0];
assert.equal(poster.variant.id,'58148127965571');
console.log('Recommendation checks passed: budget boundaries, pet suitability, variant prices, exclusions, uniqueness and stable ordering.');
